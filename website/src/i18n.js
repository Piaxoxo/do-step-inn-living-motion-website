/** Nimmt {de, en} oder einen einfachen Wert und liefert die passende Sprache. */
export const t = (wert, sprache) =>
  wert && typeof wert === "object" && !Array.isArray(wert) ? wert[sprache] ?? wert.de : wert;

export const SpracheContext = createContext("de");
export const useSprache = () => useContext(SpracheContext);
export const useT = () => {
  const sprache = useSprache();
  return (wert) => t(wert, sprache);
};

